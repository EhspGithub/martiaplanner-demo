/**
 * Normalize Persian/Arabic characters, digits, decimal separators, and ZWNJ for deep search
 */
function normalizeSearchText(input: string): string {
  return String(input || '')
    .toLowerCase()
    .replace(/ي/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/ة/g, 'ه')
    .replace(/\u200c/g, ' ')
    .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 1776))
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 1632))
    .replace(/[٫/]/g, '.')
    .replace(/\s+/g, ' ')
    .trim();
}

